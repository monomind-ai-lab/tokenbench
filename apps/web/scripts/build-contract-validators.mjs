/**
 * Compiles the accepted UI data contract schemas into standalone validators.
 *
 * Cloudflare Workers refuse `new Function`, which is how Ajv compiles schemas at
 * runtime. Emitting the validators at build time keeps the accepted-envelope
 * assertion in `src/frontend/preview-data/contract-v1.ts` intact on workerd
 * instead of weakening it. The generated module is consumed through
 * `src/cloudflare/ajv-2020-precompiled.mjs`.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import Ajv2020 from "ajv/dist/2020.js";
import { _ } from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const repoRoot = path.resolve(import.meta.dirname, "../../..");
const contractDir = path.join(repoRoot, "contracts/ui-data-contract/v1");
const outputDir = path.resolve(import.meta.dirname, "../src/cloudflare/generated");
const outputFile = path.join(outputDir, "ui-data-contract-v1-validators.mjs");

const readJson = (file) => JSON.parse(readFileSync(path.join(contractDir, file), "utf8"));
const metaSchema = readJson("meta-schema.json");
const schema = readJson("schema.json");

// These options mirror `acceptedContractAjv` in the shared contract module.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictTypes: false,
  validateFormats: true,
  code: { source: true, esm: true, formats: _`formats` },
});
// The real implementations are injected by the format registry at runtime; the
// build only needs the names so the generated code references them.
ajv.addFormat("date-time", { type: "string", validate: () => true });
ajv.addFormat("date", { type: "string", validate: () => true });
ajv.addMetaSchema(metaSchema);
ajv.addSchema(schema);

const methods = ["models", "profile", "lifecycle", "rankings", "comparison", "subscription"];
const refs = Object.fromEntries(methods.map((method) => [method, `${schema.$id}#/$defs/${method}Envelope`]));
for (const ref of Object.values(refs)) {
  if (!ajv.getSchema(ref)) throw new Error(`Accepted contract schema does not define ${ref}.`);
}

/**
 * Ajv's `code.esm` option only changes the export syntax; the runtime helpers it
 * pulls in (`ucs2length`, `equal`, `uri`, ...) are still emitted as CommonJS
 * `require` calls, which throw in an ES module. Hoist them into real imports.
 */
function hoistRequiresToImports(source) {
  const imports = new Map();
  const rewritten = source.replace(
    /require\("([^"]+)"\)(\.default)?/gu,
    (_match, specifier, isDefault) => {
      const key = `${specifier}${isDefault ? "#default" : ""}`;
      let binding = imports.get(key);
      if (!binding) {
        binding = {
          name: `__ajvRuntime${imports.size}`,
          // Ajv emits extensionless CommonJS paths; ES module resolution needs
          // the explicit file extension.
          specifier: /\.[cm]?js$/u.test(specifier) ? specifier : `${specifier}.js`,
          isDefault: Boolean(isDefault),
        };
        imports.set(key, binding);
      }
      return binding.name;
    },
  );
  // Ajv's runtime helpers are CommonJS. Node hands back the whole `exports`
  // object as the ES default while bundlers honour `__esModule` and hand back
  // `exports.default`, so unwrap until the real value is reached.
  const interop = [
    "function __ajvInterop(module) {",
    "  let current = module;",
    '  while (current && typeof current === "object" && "default" in current) current = current.default;',
    "  return current;",
    "}",
  ].join("\n");
  const statements = [...imports.values()].map(({ name, specifier, isDefault }) =>
    isDefault
      ? `import * as ${name}Namespace from "${specifier}";\nconst ${name} = __ajvInterop(${name}Namespace);`
      : `import * as ${name} from "${specifier}";`,
  );
  return [interop, statements.join("\n"), rewritten].filter(Boolean).join("\n");
}

const generated = hoistRequiresToImports(standaloneCode(ajv, refs));
if (/new Function|\beval\(/u.test(generated)) {
  throw new Error("Generated validators still rely on runtime code generation.");
}
if (/\brequire\(/u.test(generated)) {
  throw new Error("Generated validators still contain CommonJS requires.");
}

mkdirSync(outputDir, { recursive: true });
writeFileSync(
  outputFile,
  [
    "// Generated by scripts/build-contract-validators.mjs. Do not edit.",
    'import { formats } from "../ajv-format-registry.mjs";',
    "",
    generated,
  ].join("\n"),
);
console.log(`Wrote ${methods.length} precompiled contract validators to ${outputFile}`);
